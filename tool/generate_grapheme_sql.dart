import 'dart:io';
import 'dart:convert';
import 'package:characters/characters.dart';
import 'package:characters/src/grapheme_clusters/table.dart' as table;
import 'package:characters/src/grapheme_clusters/constants.dart' as constants;

void main(List<String> args) {
  if (args.contains('--cases')) {
    final config =
        jsonDecode(File('.dart_tool/package_config.json').readAsStringSync())
            as Map;
    final root = Uri.parse(
      (config['packages'] as List).singleWhere(
            (p) => p['name'] == 'characters',
          )['rootUri']
          as String,
    );
    final file = File.fromUri(
      Uri.parse(
        '$root/',
      ).resolve('third_party/Unicode_Consortium/GraphemeBreakTest.txt'),
    );
    final cases = <Map<String, Object>>[];
    for (final line in file.readAsLinesSync()) {
      final parts = line.split('#').first.trim().split(RegExp(r'\s+'));
      final points = parts
          .where((p) => p != '÷' && p != '×' && p.isNotEmpty)
          .map((p) => int.parse(p, radix: 16))
          .toList();
      // PostgreSQL text deliberately cannot represent NUL; the UI rejects it.
      if (points.isEmpty || points.contains(0)) continue;
      final value = String.fromCharCodes(points);
      cases.add({'value': value, 'expected': value.characters.length});
    }
    stdout.write(jsonEncode(cases));
    return;
  }
  final starts = <int>[];
  final categories = <int>[];
  var previous = -1;
  for (var cp = 0; cp <= 0x10ffff; cp++) {
    final category = cp <= 0xffff
        ? table.low(cp)
        : table.high((cp - 0x10000) >> 10, (cp - 0x10000) & 1023);
    if (category != previous) {
      starts.add(cp);
      categories.add(category);
      previous = category;
    }
  }
  final transitions = <int>[
    for (var state = 0; state <= constants.stateSoT; state += 20)
      for (var category = 0; category < 20; category++)
        table.move(state, category),
  ];
  File('supabase/migrations/202611270006_grapheme_empty.sql').writeAsStringSync(
    '''
-- Generated by dart run tool/generate_grapheme_sql.dart; characters 1.4.1.
-- Dart project authors (2019, 2023), BSD-3-Clause; Unicode data license.
-- Full notices: backend/licenses/characters.txt and unicode.txt.
-- No runtime extension or network dependency. Same forward automaton as client.
create or replace function app_private.grapheme_length(value text) returns integer
language plpgsql immutable strict set search_path = '' as \$\$
declare
  starts constant integer[] := array[${starts.join(',')}];
  categories constant integer[] := array[${categories.join(',')}];
  transitions constant integer[] := array[${transitions.join(',')}];
  state integer := ${constants.stateSoT}; result integer := 0;
  cp integer; lo integer; hi integer; mid integer; ch text;
begin
  if value = '' then return 0; end if;
  foreach ch in array regexp_split_to_array(value, '') loop
    cp := ascii(ch); lo := 1; hi := array_length(starts,1);
    while lo < hi loop
      mid := (lo + hi + 1) / 2;
      if starts[mid] <= cp then lo := mid; else hi := mid - 1; end if;
    end loop;
    state := transitions[(state & -4) + categories[lo] + 1];
    result := result + (state & 1);
  end loop;
  return result;
end;
\$\$;
revoke all on function app_private.grapheme_length(text) from public,anon,authenticated,service_role;
''',
  );
}
